package com.example.android_manager.data.risk

import android.content.Context
import android.content.pm.ApplicationInfo
import android.content.pm.PackageInfo
import android.content.pm.PackageManager
import com.example.android_manager.data.scanner.ApkAnalysisResult
import com.example.android_manager.model.ComponentExposureBreakdown
import com.example.android_manager.model.RiskAssessment
import com.example.android_manager.model.RiskFactor
import com.example.android_manager.model.RiskLevel
import com.example.android_manager.model.RiskRecommendation
import com.example.android_manager.model.VulnerabilityFinding
import java.io.File
import kotlin.math.roundToInt

/**
 * APVM Risk Assessment Engine repository.
 * Aggregates multi-dimensional risk vectors into a unified security risk assessment.
 */
class RiskAssessmentRepository(
    private val context: Context
) {

    private val permissionEvaluator = PermissionRiskEvaluator()
    private val componentEvaluator = ComponentExposureEvaluator()
    private val vulnerabilityEvaluator = VulnerabilityRiskEvaluator()
    private val configurationEvaluator = ConfigurationRiskEvaluator()

    /**
     * Calculates risk assessment from an APK analysis result generated by the APK Scanner.
     */
    fun assessApkResult(analysisResult: ApkAnalysisResult): RiskAssessment {
        val apkInfo = analysisResult.apkInfo
        val findings = analysisResult.findings

        // Extract permissions from findings or known requested permissions
        val permissionNames = findings
            .filter { it.affectedComponent == "Permission" || it.name.startsWith("Permission:") }
            .map { it.evidence.ifBlank { it.name.substringAfter("Permission: ") } }

        val permResult = permissionEvaluator.evaluate(permissionNames)
        val vulnResult = vulnerabilityEvaluator.evaluate(findings)

        // Evaluate exposed components from findings
        val expActCount = findings.count { it.name.contains("Activity", ignoreCase = true) && it.name.contains("Exported", ignoreCase = true) }
        val expSrvCount = findings.count { it.name.contains("Service", ignoreCase = true) && it.name.contains("Exported", ignoreCase = true) }
        val expRcvCount = findings.count { it.name.contains("Receiver", ignoreCase = true) && it.name.contains("Exported", ignoreCase = true) }
        val expPrvCount = findings.count { it.name.contains("Provider", ignoreCase = true) && it.name.contains("Exported", ignoreCase = true) }

        val compResult = componentEvaluator.evaluateRaw(
            exportedActivities = expActCount,
            exportedServices = expSrvCount,
            exportedReceivers = expRcvCount,
            exportedProviders = expPrvCount
        )

        // Configuration risk from SDK versions and findings
        val isDebuggable = findings.any { it.name.contains("Debuggable", ignoreCase = true) }
        val allowBackup = findings.any { it.name.contains("Backup", ignoreCase = true) }
        val usesCleartext = findings.any { it.name.contains("Cleartext", ignoreCase = true) }

        val configPenalty = (if (isDebuggable) 30 else 0) +
                (if (allowBackup) 12 else 0) +
                (if (usesCleartext) 16 else 0) +
                (if ((apkInfo.targetSdk ?: 34) < 31) 15 else 0)

        val configScore = configPenalty.coerceIn(0, 100)
        val configLevel = RiskLevel.fromScore(configScore)

        // Calculate weighted composite score
        // Formula: 30% Permissions, 35% Vulnerabilities, 20% Component Exposure, 15% Configuration
        val rawComposite = (permResult.score * 0.30) +
                (vulnResult.score * 0.35) +
                (compResult.score * 0.20) +
                (configScore * 0.15)

        val overallScore = rawComposite.roundToInt().coerceIn(0, 100)
        val overallLevel = RiskLevel.fromScore(overallScore)

        val allFactors = mutableListOf<RiskFactor>()
        allFactors.addAll(vulnResult.contributingFactors)
        allFactors.addAll(permResult.contributingFactors)
        allFactors.addAll(compResult.contributingFactors)

        val recommendations = generateRecommendations(
            isDebuggable = isDebuggable,
            allowBackup = allowBackup,
            usesCleartext = usesCleartext,
            compBreakdown = compResult.breakdown,
            vulnFindings = findings,
            permResult = permResult
        )

        return RiskAssessment(
            targetName = apkInfo.appName ?: apkInfo.packageName,
            packageName = apkInfo.packageName,
            versionName = apkInfo.versionName,
            overallScore = overallScore,
            overallLevel = overallLevel,
            permissionRisk = permResult.score,
            permissionRiskLevel = permResult.level,
            vulnerabilityRisk = vulnResult.score,
            vulnerabilityRiskLevel = vulnResult.level,
            componentExposureRisk = compResult.score,
            componentExposureRiskLevel = compResult.level,
            configurationRisk = configScore,
            configurationRiskLevel = configLevel,
            contributingFactors = allFactors.sortedByDescending { it.scorePenalty },
            detectedCombinations = permResult.combinations,
            componentBreakdown = compResult.breakdown,
            recommendations = recommendations,
            isSystemApp = false
        )
    }

    /**
     * Generates prioritized actionable mitigations for identified risks.
     */
    private fun generateRecommendations(
        isDebuggable: Boolean,
        allowBackup: Boolean,
        usesCleartext: Boolean,
        compBreakdown: ComponentExposureBreakdown,
        vulnFindings: List<VulnerabilityFinding>,
        permResult: PermissionRiskResult
    ): List<RiskRecommendation> {
        val list = mutableListOf<RiskRecommendation>()

        if (isDebuggable) {
            list.add(
                RiskRecommendation(
                    id = "REC_DEBUG",
                    title = "Disable Debug Mode in Production",
                    action = "Set android:debuggable=\"false\" in AndroidManifest.xml before deploying to end-user devices.",
                    priority = RiskLevel.CRITICAL
                )
            )
        }

        if (compBreakdown.totalExportedProviders > 0) {
            list.add(
                RiskRecommendation(
                    id = "REC_PRV",
                    title = "Protect Exported Content Providers",
                    action = "Enforce custom signature-level readPermission and writePermission attributes on all exported content providers.",
                    priority = RiskLevel.CRITICAL
                )
            )
        }

        if (compBreakdown.totalExportedServices > 0) {
            list.add(
                RiskRecommendation(
                    id = "REC_SRV",
                    title = "Restrict Exported Background Services",
                    action = "Set android:exported=\"false\" unless the service is intentionally meant for inter-app communication.",
                    priority = RiskLevel.HIGH
                )
            )
        }

        if (usesCleartext) {
            list.add(
                RiskRecommendation(
                    id = "REC_HTTPS",
                    title = "Enforce HTTPS Traffic Only",
                    action = "Configure a network_security_config.xml with cleartextTrafficPermitted=\"false\" to prevent MITM attacks.",
                    priority = RiskLevel.HIGH
                )
            )
        }

        if (allowBackup) {
            list.add(
                RiskRecommendation(
                    id = "REC_BACKUP",
                    title = "Disable Insecure ADB Backups",
                    action = "Set android:allowBackup=\"false\" to protect sensitive SQLite databases and SharedPreferences from ADB dumps.",
                    priority = RiskLevel.MEDIUM
                )
            )
        }

        if (permResult.combinations.isNotEmpty()) {
            list.add(
                RiskRecommendation(
                    id = "REC_PERM_COMBO",
                    title = "Audit Sensitive Permission Combinations",
                    action = "Review ${permResult.combinations.size} dangerous permission combinations and apply the Principle of Least Privilege.",
                    priority = RiskLevel.HIGH
                )
            )
        }

        vulnFindings.filter { it.severity.isHighOrCritical() }.take(3).forEach { vuln ->
            if (vuln.recommendation.isNotBlank()) {
                list.add(
                    RiskRecommendation(
                        id = "REC_VULN_${vuln.name.hashCode()}",
                        title = "Fix ${vuln.name}",
                        action = vuln.recommendation,
                        priority = vuln.severity,
                        targetComponent = vuln.affectedComponent
                    )
                )
            }
        }

        return list
    }
}